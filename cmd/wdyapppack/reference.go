func configFields() []confdoc.Field {
	return append(bundle.ConfigFields(), distribution.ConfigFields()...)
}

func schema() []byte {
	return confdoc.Schema(
		"https://github.com/worldiety/wdyapppack/wdyapppack.schema.json",
		"wdyapppack configuration",
		"Describes a macOS application bundle built from a prebuilt program, and how it is signed, notarized and packaged. Generated by: wdyapppack schema",
		configFields(),
	)
}

func schemaCommand() cli.Command {
	return cli.Command{
		Name:    "schema",
		Group:   "Reference",
		Summary: "print the JSON Schema of the configuration file",
		Description: `Prints a JSON Schema (draft 2020-12) of wdyapppack.json, with a description of every field. Save it next to the configuration and editors such as VS Code complete and check the file as you type; init writes "$schema": "wdyapppack.schema.json" for this.

The schema refuses unknown fields, exactly as wdyapppack does.`,
		Examples: []cli.Example{
			cli.Ex("save the schema next to the configuration", "wdyapppack schema > wdyapppack.schema.json"),
		},
		SeeAlso:   []string{"config", "init"},
		Platforms: "every operating system.",
		Run: func(inv *cli.Invocation) (cli.Report, error) {
			s := schema()
			var data any = string(s)
			if inv.Format == "json" {
				data = rawJSON(s)
			}
			return cli.Report{Raw: true, Text: string(s), Data: data}, nil
		},
	}
}

type rawJSON []byte

func (r rawJSON) MarshalJSON() ([]byte, error) { return r, nil }

// Version reports what wdyapppack was built from.
type Version struct {
	Version  string `json:"version"`
	Revision string `json:"revision,omitempty"`
	Time     string `json:"time,omitempty"`
	Modified bool   `json:"modified,omitempty"`
	Go       string `json:"go"`
}

// version is set at link time with -ldflags "-X main.version=1.2.3"; without
// it, the module version recorded by the go tool is used.
var version = ""

func currentVersion() Version {
	v := Version{Version: version, Go: "unknown"}
	if info, ok := debug.ReadBuildInfo(); ok {
		v.Go = info.GoVersion
		if v.Version == "" {
			v.Version = info.Main.Version
		}
		for _, s := range info.Settings {
			switch s.Key {
			case "vcs.revision":
				v.Revision = s.Value
			case "vcs.time":
				v.Time = s.Value
			case "vcs.modified":
				v.Modified = s.Value == "true"
			}
		}
	}
	if v.Version == "" {
		v.Version = "(devel)"
	}
	return v
}

func versionCommand() cli.Command {
	return cli.Command{
		Name:        "version",
		Group:       "Reference",
		Summary:     "print the version of wdyapppack",
		Description: "Prints the version of wdyapppack, the source revision it was built from and the Go version that built it. --version without a command does the same.",
		Examples:    []cli.Example{cli.Ex("the version, machine readable", "wdyapppack version --format json")},
		Platforms:   "every operating system.",
		Run: func(inv *cli.Invocation) (cli.Report, error) {
			v := currentVersion()
			text := "wdyapppack " + v.Version
			if v.Revision != "" {
				r := v.Revision
				if len(r) > 12 {
					r = r[:12]
				}
				text += " (" + r
				if v.Modified {
					text += ", modified"
				}
				text += ")"
			}
			text += ", " + v.Go + "\n"
			return cli.Report{Text: text, Data: v}, nil
		},
	}
}

// generalTopics are the topics that belong to the program as a whole.
func generalTopics(app *cli.App) []cli.Topic {
	wrapped := func(name string) func() string {
		return func() string { return cli.Wrap(text(name), 0, cli.Width) }
	}
	return []cli.Topic{
		{Name: "config", Summary: "wdyapppack.json, field by field", Body: configTopic},
		{Name: "recipes", Summary: "complete command sequences for typical cases", Body: wrapped("recipes")},
		{Name: "ci", Summary: "a build server: secrets in the environment, no keychain setup", Body: wrapped("ci")},
		{Name: "agents", Summary: "how an AI agent or a script should use wdyapppack", Body: wrapped("agents")},
		{Name: "errors", Summary: "every error and note code, with what it means", Body: app.ErrorsTopic},
		{Name: "exit-codes", Summary: "what each exit code means", Body: app.ExitCodesTopic},
		{Name: "requirements", Summary: "what wdyapppack is built to do, and why", Body: requirementsTopic},
	}
}

func configTopic() string {
	var b strings.Builder
	b.WriteString(cli.Wrap(text("config"), 0, cli.Width))
	b.WriteString("\nFIELDS\n\n")
	b.WriteString(confdoc.Text(configFields(), func(t string, indent int) string { return cli.Wrap(t, indent, cli.Width) }))
	return b.String()
}

func requirementsTopic() string {
	var b strings.Builder
	b.WriteString(cli.Wrap("wdyapppack is specified as a set of requirements, each traced to the code that satisfies it and the test that demonstrates it (with speclink). They are compiled into the program, so this list is the one the program was built to. A requirement's ID can be searched for in the source code.", 0, cli.Width))
	reqs := spec.Requirements()
	kinds := []spec.Kind{spec.Functional, spec.NonFunctional, spec.Constraint, spec.Decision}
	titles := map[spec.Kind]string{spec.Functional: "WHAT IT DOES", spec.NonFunctional: "HOW IT BEHAVES", spec.Constraint: "CONSTRAINTS", spec.Decision: "DECISIONS"}
	for _, k := range kinds {
		fmt.Fprintf(&b, "\n%s\n", titles[k])
		for _, r := range reqs {
			if r.Kind != k {
				continue
			}
			fmt.Fprintf(&b, "\n  %s  %s\n", r.ID, r.Title)
			b.WriteString(cli.Wrap(r.Text, 4, cli.Width))
			if r.Rationale != "" {
				b.WriteString(cli.Wrap("Why: "+r.Rationale, 4, cli.Width))
			}
			if r.Consequences != "" {
				b.WriteString(cli.Wrap("Cost: "+r.Consequences, 4, cli.Width))
			}
		}
	}
	return b.String()
}
